// Normalizar Texto (com proteção)
function normalizeString(str) {
    if (!str || typeof str !== 'string') return '';
    return str.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

// Classificar Nível
function levelClass(level) {
    if (!level) return '';
    const l = normalizeString(level);
    if (l.includes('basico') || l.includes('fundamental')) return 'basico';
    if (l.includes('intermediari')) return 'intermediario';
    if (l.includes('avancad') || l.includes('medio') || l.includes('superior')) return 'avancado';
    return '';
}

// Traduzir Nível
function levelName(levelStr) {
    if (!levelStr) return '';
    const l = normalizeString(levelStr);
    if (l.includes('basico')) return t('level.basico');
    if (l.includes('intermediari')) return t('level.intermediario');
    if (l.includes('avancad')) return t('level.avancado');
    if (l.includes('fundamental')) return t('level.ensino_fundamental');
    if (l.includes('medio')) return t('level.ensino_medio');
    return levelStr; // Fallback
}

