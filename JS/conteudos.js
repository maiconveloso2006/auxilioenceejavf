    if (type === 'all' || type === 'exercicio') count += contentData.exercicios.filter(i => subjectKey === 'all' || i.subjectKey === subjectKey).length;
    if (type === 'all' || type === 'simulado') count += contentData.simulados.filter(i => subjectKey === 'all' || i.subjectKey === subjectKey).length;
