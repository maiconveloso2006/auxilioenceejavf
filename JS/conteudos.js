function applyFilters() {
    if (!contentSections || contentSections.length === 0) {
        console.error('❌ contentSections está vazio! Verifique se o script está no final do body.');
        contentSections = document.querySelectorAll('.content-section');
        if (contentSections.length === 0) return;
    }

    const query = normalizeString(searchInput ? searchInput.value.trim() : '');
    const hasSearch = query.length > 0;
    let anyVisible = false;

    if (searchClearBtn) searchClearBtn.classList.toggle('show', hasSearch);

    contentSections.forEach(section => {
        const sectionType = section.dataset.type;
        const typeHidden = activeType !== 'all' && activeType !== sectionType;
        const cards = section.querySelectorAll('.item-card');
        let sectionHasVisible = false;

        cards.forEach(card => {
            const cardSubject = card.dataset.subject || 'all';
            const cardTitle = card.dataset.title || '';
            const matchSubject = activeSubject === 'all' || cardSubject === activeSubject;
            const matchSearch = !hasSearch || cardTitle.includes(query);
            const visible = matchSubject && matchSearch && !typeHidden;

            card.style.display = visible ? '' : 'none';
            if (visible) sectionHasVisible = true;
        });

        section.style.display = sectionHasVisible ? '' : 'none';
        if (sectionHasVisible) anyVisible = true;
    });

    const noResults = document.getElementById('noResultsMessage');
    if (noResults) noResults.style.display = anyVisible ? 'none' : '';

    updateAllCounts();
    updateSelectionBanner();
}

